//! Reproducible virtual-anchor lock file — `anchors.lock` (PLAN 5.1.4).
//!
//! One resolved anchor pipeline (see [`crate::anchors_map::resolve`]) serializes
//! to a small, line-oriented text file that records, for each virtual name, the
//! concrete provider that won, the CAS object id behind it and the virtual
//! symlink that points at it. Re-running the same map against the same CAS
//! produces a **byte-identical** file; the reader validates it back into the
//! typed structure or fails with a field-addressed error.
//!
//! # Format (version 1)
//!
//! ```text
//! # ExtOS virtual anchor lock (PLAN 5.1.4) — generated by libextos vlock; do not edit.
//! format 1
//! generator libextos-anchors
//! count 2
//!
//! virtual "libc.so.6" origin "archlinux" package "glibc" version "2.39" object "BLAKE3-…" link "refs/virtual/libc.so.6"
//! virtual "libssl.so.3" origin "fedora" package "openssl" version "3.0.11" object "BLAKE3-…" link "refs/virtual/libssl.so.3"
//! ```
//!
//! Rules enforced by the reader:
//!
//! * the first line must be the header comment shown above;
//! * `format` must be [`LOCK_FORMAT_VERSION`] and `generator` must be
//!   [`GENERATOR_TAG`] — a lock written by anything else is a typed error, never
//!   guessed at;
//! * `count` must equal the number of `virtual` lines;
//! * every `virtual` line carries exactly the six keys above (any order, no
//!   duplicates, no unknowns); `link` must be the canonical
//!   `refs/virtual/<virtual>` path, so a lock whose body drifted from its keys
//!   is rejected;
//! * entries must be strictly sorted by virtual name (ascending bytes) and
//!   unique — the writer guarantees it, the reader verifies it;
//! * all names/versions/object ids are re-validated with the CAS rules
//!   ([`crate::cas::validate_virtual_name`], [`crate::cas::validate_ref_component`]).
//!
//! Values are quoted tokens with no escape sequences, which is sufficient
//! because every accepted value comes from the validated identifier sets above.
//!
//! # Determinism and atomicity
//!
//! Entries are sorted by `virtual_name` ascending in [`AnchorLock::new`], so the
//! output never depends on input order. [`AnchorLock::write`] only rewrites when
//! the rendered bytes differ (byte-identical rerun reports "unchanged") and
//! writes through a same-directory temporary file plus `rename` — the same
//! discipline as the BLS writer (replicated minimally here because that helper
//! is private to `forge::bls`).
//!
//! # Drift check
//!
//! [`AnchorLock::verify`] re-resolves every entry against a live CAS: the
//! virtual symlink must still name the locked ref and that ref must still name
//! the locked object. A mismatch is [`ExtosError::CasIntegrity`].

use std::fs;
use std::io::Write;
use std::path::Path;

use crate::anchors_map::AnchorResolution;
use crate::cas::{CasRepository, is_valid_virtual_name, validate_ref_component};
use crate::error::ExtosError;

/// Version of the lock format this module writes and accepts.
pub const LOCK_FORMAT_VERSION: u32 = 1;

/// Generator tag recorded in (and required from) the header.
pub const GENERATOR_TAG: &str = "libextos-anchors";

/// First line of every lock file (also the reader's magic check).
pub const HEADER_LINE: &str =
    "# ExtOS virtual anchor lock (PLAN 5.1.4) — generated by libextos vlock; do not edit.";

/// Prefix of the per-anchor line.
const ENTRY_KEY: &str = "virtual";

/// One pinned anchor: virtual name → concrete ref, object id and symlink.
#[derive(Debug, Clone, PartialEq, Eq, PartialOrd, Ord)]
pub struct AnchorLockEntry {
    /// Virtual name (`libssl.so.3`).
    pub virtual_name: String,
    /// Winning origin.
    pub origin: String,
    /// Winning package.
    pub package: String,
    /// Winning concrete version.
    pub version: String,
    /// CAS object id of the winning ref (the ref's own object, no new digest).
    pub object: String,
    /// Virtual symlink path, `refs/virtual/<virtual_name>`.
    pub link: String,
}

impl AnchorLockEntry {
    /// Winning provider label, `origin/package`.
    pub fn provider(&self) -> String {
        format!("{}/{}", self.origin, self.package)
    }

    /// Concrete ref, `origin/package/version`.
    pub fn ref_label(&self) -> String {
        format!("{}/{}/{}", self.origin, self.package, self.version)
    }

    /// The canonical link path for a virtual name.
    pub fn link_for(virtual_name: &str) -> String {
        format!("refs/virtual/{virtual_name}")
    }
}

/// A validated, deterministically ordered anchor lock (PLAN 5.1.4).
///
/// Construction ([`AnchorLock::new`], [`AnchorLock::parse`],
/// [`AnchorLock::from_resolution`]) sorts by virtual name and rejects
/// duplicates, so a lock value is always canonical.
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct AnchorLock {
    entries: Vec<AnchorLockEntry>,
}

impl AnchorLock {
    /// Build a lock from entries, sorting them and rejecting duplicates.
    ///
    /// Every field is re-validated, so a hand-built lock cannot smuggle a path
    /// separator or an empty object id into the file.
    pub fn new(mut entries: Vec<AnchorLockEntry>) -> Result<Self, ExtosError> {
        for entry in &entries {
            validate_entry(entry, &entry.virtual_name)?;
        }
        entries.sort();
        for pair in entries.windows(2) {
            if pair[0].virtual_name == pair[1].virtual_name {
                return Err(ExtosError::Serialization(format!(
                    "anchor lock: duplicate virtual name {:?}",
                    pair[0].virtual_name
                )));
            }
        }
        Ok(Self { entries })
    }

    /// Build the lock for a resolved anchor pipeline.
    ///
    /// `link` is rendered as the canonical `refs/virtual/<name>`; the object id
    /// is the one already resolved from the concrete ref (no digest is taken).
    pub fn from_resolution(resolution: &AnchorResolution) -> Result<Self, ExtosError> {
        let entries = resolution
            .anchors
            .iter()
            .map(|anchor| AnchorLockEntry {
                virtual_name: anchor.virtual_name.clone(),
                origin: anchor.origin.clone(),
                package: anchor.package.clone(),
                version: anchor.version.clone(),
                object: anchor.object.clone(),
                link: AnchorLockEntry::link_for(&anchor.virtual_name),
            })
            .collect();
        Self::new(entries)
    }

    /// Entries in canonical (virtual name ascending) order.
    pub fn entries(&self) -> &[AnchorLockEntry] {
        &self.entries
    }

    /// The entry pinned for one virtual name.
    pub fn get(&self, virtual_name: &str) -> Option<&AnchorLockEntry> {
        self.entries
            .iter()
            .find(|entry| entry.virtual_name == virtual_name)
    }

    /// Number of pinned anchors.
    pub fn len(&self) -> usize {
        self.entries.len()
    }

    /// Whether the lock pins nothing (a valid, empty lock).
    pub fn is_empty(&self) -> bool {
        self.entries.is_empty()
    }

    /// Render the lock file bytes.
    ///
    /// Deterministic: header, counters, then one line per entry in sorted order.
    /// Rendering the same lock twice always yields the same string.
    pub fn render(&self) -> String {
        let mut out = String::new();
        out.push_str(HEADER_LINE);
        out.push('\n');
        out.push_str(&format!("format {LOCK_FORMAT_VERSION}\n"));
        out.push_str(&format!("generator {GENERATOR_TAG}\n"));
        out.push_str(&format!("count {}\n", self.entries.len()));
        out.push('\n');
        for entry in &self.entries {
            out.push_str(&format!(
                "{ENTRY_KEY} \"{}\" origin \"{}\" package \"{}\" version \"{}\" object \"{}\" link \"{}\"\n",
                entry.virtual_name, entry.origin, entry.package, entry.version, entry.object,
                entry.link
            ));
        }
        out
    }

    /// Write the lock to `path`, atomically and idempotently.
    ///
    /// Returns `Ok(false)` when the file already has exactly the rendered bytes
    /// (no write happens) and `Ok(true)` when it was written. The write goes to
    /// a temporary file in the same directory and is renamed into place, so a
    /// concurrent reader never observes a partial lock.
    pub fn write(&self, path: &Path) -> Result<bool, ExtosError> {
        let content = self.render();
        if let Ok(existing) = fs::read_to_string(path) {
            if existing == content {
                return Ok(false);
            }
        }
        write_atomic(path, content.as_bytes())?;
        Ok(true)
    }

    /// Parse lock text. `source` names the document in error messages.
    pub fn parse(text: &str, source: &str) -> Result<Self, ExtosError> {
        let mut lines = text.lines().enumerate().map(|(i, line)| (i + 1, line));

        let (header_line_no, header) = lines
            .next()
            .ok_or_else(|| parse_error(source, 1, "empty lock file"))?;
        if header.trim_end() != HEADER_LINE {
            return Err(parse_error(
                source,
                header_line_no,
                format!("missing header line {HEADER_LINE:?}"),
            ));
        }

        let mut format_seen = false;
        let mut generator_seen = false;
        let mut count: Option<usize> = None;
        let mut entries = Vec::new();

        for (line_no, line) in lines {
            let trimmed = line.trim();
            if trimmed.is_empty() || trimmed.starts_with('#') {
                continue;
            }
            let tokens = split_tokens(trimmed).map_err(|message| parse_error(source, line_no, message))?;
            let Some((key, rest)) = tokens.split_first() else {
                continue;
            };
            match key.as_str() {
                "format" => {
                    if format_seen {
                        return Err(parse_error(source, line_no, "duplicate 'format' line"));
                    }
                    format_seen = true;
                    let value = single_value(rest, source, line_no, "format")?;
                    let version: u32 = value.parse().map_err(|_| {
                        parse_error(source, line_no, format!("invalid format version {value:?}"))
                    })?;
                    if version != LOCK_FORMAT_VERSION {
                        return Err(parse_error(
                            source,
                            line_no,
                            format!(
                                "unsupported lock format {version} (this build reads {LOCK_FORMAT_VERSION})"
                            ),
                        ));
                    }
                }
                "generator" => {
                    if generator_seen {
                        return Err(parse_error(source, line_no, "duplicate 'generator' line"));
                    }
                    generator_seen = true;
                    let value = single_value(rest, source, line_no, "generator")?;
                    if value != GENERATOR_TAG {
                        return Err(parse_error(
                            source,
                            line_no,
                            format!("unexpected generator {value:?} (expected {GENERATOR_TAG:?})"),
                        ));
                    }
                }
                "count" => {
                    if count.is_some() {
                        return Err(parse_error(source, line_no, "duplicate 'count' line"));
                    }
                    let value = single_value(rest, source, line_no, "count")?;
                    let parsed: usize = value.parse().map_err(|_| {
                        parse_error(source, line_no, format!("invalid count {value:?}"))
                    })?;
                    count = Some(parsed);
                }
                ENTRY_KEY => {
                    entries.push(parse_entry(rest, source, line_no)?);
                }
                other => {
                    return Err(parse_error(
                        source,
                        line_no,
                        format!("unknown lock key {other:?}"),
                    ));
                }
            }
        }

        if !format_seen {
            return Err(parse_error(source, 0, "missing 'format' line"));
        }
        if !generator_seen {
            return Err(parse_error(source, 0, "missing 'generator' line"));
        }
        let count =
            count.ok_or_else(|| parse_error(source, 0, "missing 'count' line"))?;
        if count != entries.len() {
            return Err(parse_error(
                source,
                0,
                format!(
                    "count says {count} but {} virtual entries were read",
                    entries.len()
                ),
            ));
        }

        // Canonical order is part of the format; verify it before sorting so a
        // hand-edited file is reported instead of silently normalized.
        for pair in entries.windows(2) {
            if pair[0].virtual_name >= pair[1].virtual_name {
                return Err(parse_error(
                    source,
                    0,
                    format!(
                        "entries are not strictly sorted by virtual name: {:?} then {:?}",
                        pair[0].virtual_name, pair[1].virtual_name
                    ),
                ));
            }
        }

        Self::new(entries).map_err(|error| match error {
            ExtosError::Serialization(message) => parse_error(source, 0, message),
            other => other,
        })
    }

    /// Parse a lock file; the path doubles as the error source.
    pub fn parse_file(path: &Path) -> Result<Self, ExtosError> {
        let text = fs::read_to_string(path)?;
        Self::parse(&text, &path.display().to_string())
    }

    /// Verify every entry against a live CAS (drift check).
    ///
    /// Fails with [`ExtosError::CasIntegrity`] when the virtual symlink is
    /// missing or points elsewhere, or when the locked ref resolves to a
    /// different object. The repository is never modified.
    pub fn verify(&self, repo: &CasRepository) -> Result<(), ExtosError> {
        for entry in &self.entries {
            let resolved = repo.resolve_virtual(&entry.virtual_name)?;
            if resolved.origin != entry.origin
                || resolved.name != entry.package
                || resolved.version != entry.version
            {
                return Err(ExtosError::CasIntegrity {
                    expected: entry.ref_label(),
                    actual: resolved.label(),
                });
            }
            let object = repo.resolve_ref(&entry.origin, &entry.package, &entry.version)?;
            if object != entry.object {
                return Err(ExtosError::CasIntegrity {
                    expected: entry.object.clone(),
                    actual: object,
                });
            }
        }
        Ok(())
    }
}

// ─── Parsing helpers ────────────────────────────────────────────

fn validate_entry(entry: &AnchorLockEntry, field: &str) -> Result<(), ExtosError> {
    let fail = |message: String| ExtosError::Serialization(format!("anchor lock {field}: {message}"));
    if !is_valid_virtual_name(&entry.virtual_name) {
        return Err(fail(format!(
            "invalid virtual name {:?}",
            entry.virtual_name
        )));
    }
    validate_ref_component(&entry.origin, "origin").map_err(|e| fail(e.to_string()))?;
    validate_ref_component(&entry.package, "package").map_err(|e| fail(e.to_string()))?;
    validate_ref_component(&entry.version, "version").map_err(|e| fail(e.to_string()))?;
    if entry.object.is_empty()
        || !entry
            .object
            .chars()
            .all(|c| c.is_ascii_alphanumeric() || matches!(c, '-' | '_' | '.'))
    {
        return Err(fail(format!("invalid CAS object id {:?}", entry.object)));
    }
    let expected_link = AnchorLockEntry::link_for(&entry.virtual_name);
    if entry.link != expected_link {
        return Err(fail(format!(
            "link {:?} does not match the canonical {expected_link:?}",
            entry.link
        )));
    }
    Ok(())
}

const ENTRY_KEYS: [&str; 6] = ["virtual", "origin", "package", "version", "object", "link"];

fn parse_entry(
    rest: &[String],
    source: &str,
    line_no: usize,
) -> Result<AnchorLockEntry, ExtosError> {
    // `rest` = [name, "origin", <o>, "package", <p>, "version", <v>, "object", <id>, "link", <l>].
    let Some((name, fields)) = rest.split_first() else {
        return Err(parse_error(
            source,
            line_no,
            format!("expected a virtual name after {ENTRY_KEY:?}"),
        ));
    };
    if fields.len() != (ENTRY_KEYS.len() - 1) * 2 {
        return Err(parse_error(
            source,
            line_no,
            format!(
                "expected origin/package/version/object/link pairs after the virtual name, got {} tokens",
                fields.len()
            ),
        ));
    }

    let mut values = std::collections::BTreeMap::new();
    for pair in fields.chunks_exact(2) {
        let key = pair[0].as_str();
        if !ENTRY_KEYS[1..].contains(&key) {
            return Err(parse_error(
                source,
                line_no,
                format!("unknown entry key {key:?}"),
            ));
        }
        if values.insert(key.to_string(), pair[1].clone()).is_some() {
            return Err(parse_error(
                source,
                line_no,
                format!("duplicate entry key {key:?}"),
            ));
        }
    }

    let mut take = |key: &str| {
        values
            .remove(key)
            .ok_or_else(|| parse_error(source, line_no, format!("missing entry key {key:?}")))
    };
    let entry = AnchorLockEntry {
        virtual_name: name.clone(),
        origin: take("origin")?,
        package: take("package")?,
        version: take("version")?,
        object: take("object")?,
        link: take("link")?,
    };
    validate_entry(&entry, name)
        .map_err(|error| parse_error(source, line_no, error.to_string()))?;
    Ok(entry)
}

fn single_value<'a>(
    rest: &'a [String],
    source: &str,
    line_no: usize,
    key: &str,
) -> Result<&'a str, ExtosError> {
    match rest {
        [value] => Ok(value.as_str()),
        _ => Err(parse_error(
            source,
            line_no,
            format!("expected exactly one value after {key:?}"),
        )),
    }
}

fn split_tokens(line: &str) -> Result<Vec<String>, String> {
    let mut tokens = Vec::new();
    let mut chars = line.chars().peekable();
    loop {
        while chars.peek().is_some_and(|c| c.is_whitespace()) {
            chars.next();
        }
        let Some(&first) = chars.peek() else {
            break;
        };
        if first == '"' {
            chars.next();
            let mut value = String::new();
            let mut closed = false;
            for ch in chars.by_ref() {
                match ch {
                    '"' => {
                        closed = true;
                        break;
                    }
                    '\\' => return Err("escape sequences are not supported in lock values".into()),
                    other => value.push(other),
                }
            }
            if !closed {
                return Err("unterminated quoted value".into());
            }
            tokens.push(value);
        } else {
            let mut value = String::new();
            while let Some(&ch) = chars.peek() {
                if ch.is_whitespace() {
                    break;
                }
                value.push(ch);
                chars.next();
            }
            tokens.push(value);
        }
    }
    Ok(tokens)
}

fn parse_error(source: &str, line: usize, message: impl Into<String>) -> ExtosError {
    ExtosError::ConfigParse {
        path: source.to_string(),
        line,
        message: format!("anchor lock: {}", message.into()),
    }
}

fn write_atomic(path: &Path, content: &[u8]) -> Result<(), ExtosError> {
    if let Some(parent) = path.parent() {
        if !parent.as_os_str().is_empty() {
            fs::create_dir_all(parent)?;
        }
    }
    let file_name = path
        .file_name()
        .map(|name| name.to_string_lossy().into_owned())
        .unwrap_or_else(|| "anchors.lock".into());
    let tmp = path.with_file_name(format!(".{file_name}.tmp-{}", std::process::id()));
    {
        let mut file = fs::File::create(&tmp)?;
        file.write_all(content)?;
        file.sync_all()?;
    }
    if let Err(error) = fs::rename(&tmp, path) {
        let _ = fs::remove_file(&tmp);
        return Err(error.into());
    }
    Ok(())
}

