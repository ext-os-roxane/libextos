#[test]
fn alpine_apkindex_translates_to_manifest() {
    let dir = tempfile::tempdir().unwrap();
    let index = dir.path().join("APKINDEX");
    fs::write(
        &index,
        "\
C:Q1aBcDeF=
P:htop
V:3.3.0-r0
A:x86_64
T:Interactive process viewer
D:musl so:libc.musl-x86_64.so.1 cmd:sh !bash
p:cmd:htop so:libhtop.so.1 htop-virtual

C:Q1gHiJkL=
P:musl
V:1.2.5-r0
D:
",
    )
    .unwrap();

    let plugin = AlpinePlugin;
    let manifest = translate(&plugin, &index);

    assert_eq!(manifest.identity.origin, "alpine");
    assert_eq!(manifest.identity.name, "htop");
    assert_eq!(manifest.identity.version, "3.3.0-r0");

    assert_package_dep(&manifest.requires, "musl", None);
    assert!(manifest.requires.iter().any(|dep| matches!(
        dep,
        DependencySpec::Capability(CapabilityRequest::Provides(soname))
            if soname == "libc.musl-x86_64.so.1"
    )));
    assert!(manifest.requires.iter().any(|dep| matches!(
        dep,
        DependencySpec::Capability(CapabilityRequest::Executable { name, .. }) if name == "sh"
    )));

    assert!(manifest.identity.aliases.contains(&"libhtop.so.1".to_string()));
    assert!(manifest
        .identity
        .aliases
        .contains(&"htop-virtual".to_string()));
    assert_eq!(manifest.capabilities.binaries, vec!["htop"]);
    assert_eq!(manifest.capabilities.libraries, vec!["libhtop.so.1"]);
}

