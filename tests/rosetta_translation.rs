//! Integration tests for PLAN.md Sub-phase 2.3 — Rosetta upstream metadata
//! translation.
//!
//! Every fixture is synthesized at test runtime inside a `tempfile` directory:
//! there are no committed binaries or sample archives. Each test drives the
//! same path ingestion uses
//! ([`RosettaPlugin::parse_metadata`] → `manifest.nix` → [`PackageManifest`])
//! and asserts the translated identity, requirements and capabilities.

use std::fs;
use std::path::Path;

use libextos::config::parse_nix;
use libextos::dependency::{CapabilityRequest, DependencySpec};
use libextos::error::ExtosError;
use libextos::manifest::PackageManifest;
use libextos::rosetta::alpine::AlpinePlugin;
use libextos::rosetta::arch::ArchPlugin;
use libextos::rosetta::debian::DebianPlugin;
use libextos::rosetta::registry::RosettaRegistry;
use libextos::rosetta::rpm::RpmPlugin;
use libextos::rosetta::void_xbps::VoidPlugin;
use libextos::rosetta::{PluginCapability, RosettaPlugin};

/// Run a plugin's PARSE path and return the parsed ExtOS manifest.
fn translate(plugin: &dyn RosettaPlugin, metadata_path: &Path) -> PackageManifest {
    let manifest_nix = plugin
        .parse_metadata(metadata_path)
        .expect("plugin should translate the fixture");
    let value = parse_nix(&manifest_nix).expect("generated manifest.nix must parse");
    PackageManifest::from_nix(&value).expect("generated manifest.nix must be a valid manifest")
}

/// Assert a requirement on an upstream package is present with a constraint.
fn assert_package_dep(deps: &[DependencySpec], name: &str, constraint: Option<&str>) {
    assert!(
        deps.iter().any(|dep| matches!(
            dep,
            DependencySpec::LooseEcosystem {
                name: dep_name,
                version_constraint,
                ..
            } if dep_name == name && version_constraint.as_deref() == constraint
        )),
        "missing dependency {name} ({constraint:?}) in {deps:?}"
    );
}

// ─── Arch ───────────────────────────────────────────────────────

#[test]
fn arch_pkginfo_translates_to_manifest() {
    let dir = tempfile::tempdir().unwrap();
    let pkginfo = dir.path().join(".PKGINFO");
    fs::write(
        &pkginfo,
        "\
# Generated by makepkg 6.1.0
pkgname = htop
pkgver = 3.3.0-1
pkgdesc = Interactive process viewer
depend = glibc
depend = ncurses>=6.4
provides = libhtop.so=1-64
provides = system-monitor=3.3
replaces = htop-legacy
",
    )
    .unwrap();

    let plugin = ArchPlugin;
    let manifest = translate(&plugin, &pkginfo);

    assert_eq!(manifest.identity.origin, "archlinux");
    assert_eq!(manifest.identity.name, "htop");
    assert_eq!(manifest.identity.version, "3.3.0-1");

    assert_package_dep(&manifest.requires, "glibc", None);
    assert_package_dep(&manifest.requires, "ncurses", Some(">=6.4"));

    assert!(manifest.identity.aliases.contains(&"libhtop.so".to_string()));
    assert!(manifest
        .identity
        .aliases
        .contains(&"system-monitor".to_string()));
    assert!(manifest.identity.aliases.contains(&"htop-legacy".to_string()));
    assert_eq!(manifest.capabilities.libraries, vec!["libhtop.so"]);
    assert_eq!(manifest.capabilities.virtual_caps, vec!["system-monitor"]);

    // The dep-translation entry point agrees with the manifest.
    let deps_json = plugin.translate_deps(&pkginfo).unwrap();
    let deps: Vec<DependencySpec> = serde_json::from_str(&deps_json).unwrap();
    assert_eq!(deps.len(), manifest.requires.len());
}

#[test]
fn arch_pkginfo_is_found_inside_a_metadata_directory() {
    // `ingest_package_with_rosetta` hands the plugin a staging `metadata/`
    // directory rather than the control file, so directory input must work.
    let dir = tempfile::tempdir().unwrap();
    let metadata_dir = dir.path().join("metadata");
    fs::create_dir_all(&metadata_dir).unwrap();
    fs::write(metadata_dir.join("PKGINFO"), "pkgname = nano\npkgver = 8.0-1\n").unwrap();

    let manifest = translate(&ArchPlugin, &metadata_dir);
    assert_eq!(manifest.identity.name, "nano");
    assert_eq!(manifest.identity.version, "8.0-1");
}

